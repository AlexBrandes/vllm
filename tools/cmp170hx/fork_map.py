"""Regenerate FORK.md: the plugin's files and the vLLM branch it runs with.

    python tools/cmp170hx/fork_map.py --vllm <vllm branch> [--base <commit>]

Run it in the plugin's checkout, in a clone that also has the vLLM branch.
The branch's upstream base is the commit its name ends with
(``vllm/<first 10 characters of the upstream commit>``), or ``--base``.
tests/cmp170hx/update_seams.py and test_modification_notices.py read the
``Upstream base:`` line.
"""

import argparse
import re
import subprocess
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
FORK_MD = REPO / "FORK.md"
BRANCH_NAME = re.compile(r"(?:^|/)vllm/([0-9a-f]{7,40})$")


def git(*args: str) -> str:
    return subprocess.run(
        ["git", "-C", str(REPO), *args], capture_output=True, text=True, check=True
    ).stdout


def upstream_base(branch: str, base: str | None = None) -> str:
    """The full upstream commit ``branch`` is based on: ``base``, else the
    commit a ``vllm/<commit>`` branch name ends with. It must be an ancestor of
    the branch."""
    named = BRANCH_NAME.search(branch)
    if base is None and named is None:
        raise SystemExit(f"{branch} is not named vllm/<upstream commit>; pass --base")
    name = base or named.group(1)
    found = subprocess.run(
        ["git", "-C", str(REPO), "rev-parse", "--verify", "-q", f"{name}^{{commit}}"],
        capture_output=True,
        text=True,
    )
    if found.returncode != 0:
        raise SystemExit(
            f"{branch}: upstream base {name!r} is not a commit in this clone; "
            "pass --base"
        )
    sha = found.stdout.strip()
    ancestor = subprocess.run(
        ["git", "-C", str(REPO), "merge-base", "--is-ancestor", sha, branch]
    )
    if ancestor.returncode != 0:
        raise SystemExit(f"{branch}: {sha} is not an ancestor of the branch")
    return sha


def fork_commits(base: str, branch: str) -> list[str]:
    """``<sha> <subject>`` of the branch's own commits, oldest first."""
    return git("log", "--reverse", "--format=%H %s", f"{base}..{branch}").splitlines()


def plugin_rows() -> list[str]:
    rows = []
    for path in sorted(git("ls-files").splitlines()):
        if path == FORK_MD.name:
            continue
        lines = (REPO / path).read_bytes().count(b"\n")
        rows.append(f"| `{path}` | {lines} |")
    return rows


def file_rows(base: str, branch: str) -> list[str]:
    rows = []
    for line in git("diff", "--numstat", "--no-renames", base, branch).splitlines():
        added, removed, path = line.split("\t")
        rows.append(f"| `{path}` | {added} | {removed} |")
    return rows


def plural(n: int, noun: str) -> str:
    return f"{n} {noun}" if n == 1 else f"{n} {noun}s"


def render(branch: str, base: str) -> str:
    tip = git("rev-parse", branch).strip()
    commits = fork_commits(base, branch)
    files = file_rows(base, branch)
    return "\n".join(
        [
            "# Fork map",
            "",
            "<!-- Generated by tools/cmp170hx/fork_map.py. Do not edit by hand. -->",
            "",
            "This branch is the `vllm-cmp170hx` plugin of Alex Brandes's vLLM fork "
            "for the NVIDIA CMP 170HX: the import package `vllm_cmp170hx`, installed "
            "on the vLLM branch below (upstream vLLM plus the fork's commits). The "
            "license is Apache-2.0, as upstream.",
            "",
            f"Upstream base: {base}",
            "",
            f"vLLM branch: vllm/{base[:10]} {tip}",
            "",
            f"Section 1 lists every file of this branch. Section 2 lists the vLLM "
            f"branch's {plural(len(commits), 'commit')} on its upstream base and the "
            f"{plural(len(files), 'upstream file')} they change. This file is not "
            "listed in its own tables.",
            "",
            "## 1. Plugin files",
            "",
            "| Path | Lines |",
            "|---|---:|",
            *plugin_rows(),
            "",
            "## 2. Changes to upstream vLLM",
            "",
            *[f"- `{c[:10]}` {c.partition(' ')[2]}" for c in commits],
            "",
            "| Upstream file | Added | Removed |",
            "|---|---:|---:|",
            *files,
            "",
        ]
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--vllm", required=True, help="the vLLM branch or commit")
    parser.add_argument("--base", help="its upstream commit (default: from its name)")
    args = parser.parse_args()
    FORK_MD.write_text(render(args.vllm, upstream_base(args.vllm, args.base)))
    print(f"wrote {FORK_MD}")


if __name__ == "__main__":
    main()
